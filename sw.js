const CACHE_PREFIX = "local-vault-app-";
const CACHE = CACHE_PREFIX + VERSION;
const SCOPE_PATH = new URL("./", self.location).pathname;

async function sha256(buffer) {
  const digest = await crypto.subtle.digest("SHA-256", buffer);
  return "sha256-" + btoa(String.fromCharCode(...new Uint8Array(digest)));
}

/** Network fetch of one app file, bypassing the HTTP cache; returns the response only if it verifies. */
async function fetchVerified(path) {
  const response = await fetch(new Request(path, { cache: "reload", credentials: "same-origin", redirect: "error" }));
  if (!response.ok) throw new Error(`fetch ${path}: ${response.status}`);
  if (await sha256(await response.clone().arrayBuffer()) !== ASSETS[path]) throw new Error(`integrity ${path}`);
  return response;
}

self.addEventListener("install", event => {
  // Fill a fresh versioned cache; any failure rejects install, so the current version keeps running.
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    for (const path of Object.keys(ASSETS)) await cache.put(path, await fetchVerified(path));
  })());
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(CACHE_PREFIX) && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

self.addEventListener("message", event => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
  if (event.data?.type === "GET_VERSION") event.ports[0]?.postMessage({ version: VERSION });
});

/** Serve one app file from the cache only if it still matches its hash; otherwise repair or refuse. */
async function serveVerified(path) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(path);
  if (cached && await sha256(await cached.clone().arrayBuffer()) === ASSETS[path]) return cached;
  try {
    const fresh = await fetchVerified(path);
    await cache.put(path, fresh.clone());
    return fresh;
  } catch {
    return new Response("Local Vault: アプリのファイルを検証できませんでした。オンラインで再読み込みしてください。", {
      status: 503,
      headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store" },
    });
  }
}

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(SCOPE_PATH)) return;
  // Any navigation inside the scope gets the app shell (works offline, ignores ?query).
  const path = request.mode === "navigate" ? "./index.html" : "./" + url.pathname.slice(SCOPE_PATH.length);
  if (!Object.hasOwn(ASSETS, path)) return; // not an app file: browser default, never cached
  event.respondWith(serveVerified(path));
});
